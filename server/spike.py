"""Spike CLI: one file in, questions JSON out.

    py server/spike.py "notes.pdf" --count 10 --provider offline
    py server/spike.py "notes.pdf" --provider gemini      (needs GEMINI_API_KEY)

Writes <input>.questions.json next to the file unless --out is given, and
prints a human-readable digest so we can judge quality at a glance.
"""

from __future__ import annotations

import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

# Windows consoles default to cp1252 and die on characters like the peso sign.
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.stderr.reconfigure(encoding="utf-8", errors="replace")

import qfgen  # noqa: E402


def digest(result: dict) -> str:
    src = result["source"]
    lines = [
        "",
        "=" * 68,
        f"  {src['file']}",
        f"  {src['pages']} page(s)  |  {src['chars']:,} chars  |  "
        f"extracted via {src['method']}  |  generated by {src['provider']}",
        f"  title: {result['title']}",
        "=" * 68,
    ]
    if src["pending_images"]:
        lines.append(f"  ! pages with no text layer: {src['pending_images']}")
    for note in result.get("notes", []):
        lines.append(f"  ! {note}")

    for q in result["questions"]:
        lines.append("")
        lines.append(f"  [{q['id']}] {q['question']}")
        for i, c in enumerate(q["choices"]):
            mark = "OK" if i == q["answer"] else "  "
            lines.append(f"        {mark} {'ABCD'[i]}. {c}")
        if q.get("explanation"):
            lines.append(f"        -> {q['explanation']}")
    lines.append("")
    lines.append(f"  {len(result['questions'])} question(s)")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description="Generate quiz questions from a reviewer file.")
    ap.add_argument("path", help="pdf, txt/md/csv, or an image")
    ap.add_argument("--count", type=int, default=10)
    ap.add_argument("--provider", default="offline", choices=["offline", "gemini", "openai"])
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--out", default="")
    args = ap.parse_args()

    try:
        result = qfgen.build(args.path, count=args.count, provider=args.provider, seed=args.seed)
    except qfgen.ExtractError as e:
        print(f"could not read that file: {e}", file=sys.stderr)
        return 1
    except qfgen.ProviderError as e:
        print(f"AI call failed: {e}", file=sys.stderr)
        return 2

    out = args.out or os.path.splitext(args.path)[0] + ".questions.json"
    with open(out, "w", encoding="utf-8") as f:
        json.dump(result, f, indent=2, ensure_ascii=False)

    print(digest(result))
    print(f"\n  written to {out}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
